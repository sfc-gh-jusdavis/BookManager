-- VIEW: TEMP.JUSDAVIS.V_OD_UNIVERSE  |  created: 2026-03-24 17:11:33.044000+00:00

create or replace view V_OD_UNIVERSE(
	SALESFORCE_ACCOUNT_ID,
	IS_ACTIVE,
	IS_CONVERTED,
	SNOWFLAKE_EDITION,
	HAS_AE,
	OD_CLOSED_WON_DATE,
	OD_FIRST_USAGE_DATE,
	DAYS_CW_TO_FIRST_USAGE,
	CAPACITY_CONVERSION_DATE,
	SIGNAL_WINDOW_TYPE,
	SIGNAL_WINDOW_END_DATE,
	SIG_PIPELINE_90D,
	SIG_TRANSFORMS_90D,
	SIG_BI_90D,
	SIG_COST_90D,
	SIG_COLLAB_90D,
	SIG_OBS_90D,
	SIG_AIML_90D,
	SIG_SPCS_90D,
	SIG_COUNT_90D,
	SIG_PIPELINE_30D,
	SIG_TRANSFORMS_30D,
	SIG_BI_30D,
	SIG_COST_30D,
	SIG_COLLAB_30D,
	SIG_OBS_30D,
	SIG_AIML_30D,
	SIG_SPCS_30D,
	SIG_COUNT_30D
) as
SELECT 
    b.SALESFORCE_ACCOUNT_ID,
    b.IS_ACTIVE,
    b.IS_CONVERTED,
    b.SNOWFLAKE_EDITION,
    b.HAS_AE,
    b.OD_CLOSED_WON_DATE,
    b.OD_FIRST_USAGE_DATE,
    b.DAYS_CW_TO_FIRST_USAGE,
    b.CAPACITY_CONVERSION_DATE,
    b.SIGNAL_WINDOW_TYPE,
    b.SIGNAL_WINDOW_END_DATE,
    -- 90-day signals
    COALESCE(s90.SIG_PIPELINE_90D, 0) AS SIG_PIPELINE_90D,
    COALESCE(s90.SIG_TRANSFORMS_90D, 0) AS SIG_TRANSFORMS_90D,
    COALESCE(s90.SIG_BI_90D, 0) AS SIG_BI_90D,
    COALESCE(s90.SIG_COST_90D, 0) AS SIG_COST_90D,
    COALESCE(s90.SIG_COLLAB_90D, 0) AS SIG_COLLAB_90D,
    COALESCE(s90.SIG_OBS_90D, 0) AS SIG_OBS_90D,
    COALESCE(s90.SIG_AIML_90D, 0) AS SIG_AIML_90D,
    COALESCE(s90.SIG_SPCS_90D, 0) AS SIG_SPCS_90D,
    COALESCE(s90.SIG_PIPELINE_90D, 0) + COALESCE(s90.SIG_TRANSFORMS_90D, 0) + 
    COALESCE(s90.SIG_BI_90D, 0) + COALESCE(s90.SIG_COST_90D, 0) + 
    COALESCE(s90.SIG_COLLAB_90D, 0) + COALESCE(s90.SIG_OBS_90D, 0) + 
    COALESCE(s90.SIG_AIML_90D, 0) + COALESCE(s90.SIG_SPCS_90D, 0) AS SIG_COUNT_90D,
    -- 30-day signals
    COALESCE(s30.SIG_PIPELINE_30D, 0) AS SIG_PIPELINE_30D,
    COALESCE(s30.SIG_TRANSFORMS_30D, 0) AS SIG_TRANSFORMS_30D,
    COALESCE(s30.SIG_BI_30D, 0) AS SIG_BI_30D,
    COALESCE(s30.SIG_COST_30D, 0) AS SIG_COST_30D,
    COALESCE(s30.SIG_COLLAB_30D, 0) AS SIG_COLLAB_30D,
    COALESCE(s30.SIG_OBS_30D, 0) AS SIG_OBS_30D,
    COALESCE(s30.SIG_AIML_30D, 0) AS SIG_AIML_30D,
    COALESCE(s30.SIG_SPCS_30D, 0) AS SIG_SPCS_30D,
    COALESCE(s30.SIG_PIPELINE_30D, 0) + COALESCE(s30.SIG_TRANSFORMS_30D, 0) + 
    COALESCE(s30.SIG_BI_30D, 0) + COALESCE(s30.SIG_COST_30D, 0) + 
    COALESCE(s30.SIG_COLLAB_30D, 0) + COALESCE(s30.SIG_OBS_30D, 0) + 
    COALESCE(s30.SIG_AIML_30D, 0) + COALESCE(s30.SIG_SPCS_30D, 0) AS SIG_COUNT_30D
FROM TEMP.JUSDAVIS.T_OD_UNIVERSE_BASE b
LEFT JOIN TEMP.JUSDAVIS.T_OD_SIGNALS_90D s90 ON s90.SALESFORCE_ACCOUNT_ID = b.SALESFORCE_ACCOUNT_ID
LEFT JOIN TEMP.JUSDAVIS.T_OD_SIGNALS_30D s30 ON s30.SALESFORCE_ACCOUNT_ID = b.SALESFORCE_ACCOUNT_ID;
